#!/usr/bin/env python3
"""Generate anti-aliased TFT_eSPI "smooth fonts" (.vlw format) as C arrays.

Source font: Barlow Semi Condensed (SIL Open Font License 1.1), see
tools/fonts/OFL.txt. The generated headers are committed so firmware builds
do not need Python or Pillow.

    python3 tools/gen_fonts.py            # writes src/fonts/*.h

VLW layout (big endian), as read by TFT_eSPI Smooth_font.cpp:
  header: gCount, version(11), fontSize, 0, ascent, descent       (6 x int32)
  glyphs: unicode, height, width, xAdvance, dY, dX, 0             (7 x int32 each)
  bitmaps: width*height bytes of 8-bit alpha per glyph
"""
import os
import struct
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "tools", "fonts")
OUT_DIR = os.path.join(ROOT, "src", "fonts")

LATIN = list(range(0x21, 0x7F)) + list(range(0xA1, 0x180))
DIGITS = [ord(c) for c in "0123456789:+-.,'/ABCDEFGHIJKLMNOPQRSTUVWXYZ"]

ASCII = list(range(0x21, 0x7F))

FONTS = [
    # name,      file,                               px, glyphs
    ("font_xs", "BarlowSemiCondensed-SemiBold.ttf", 12, ASCII),   # portrait tab bar
    ("font_s",  "BarlowSemiCondensed-SemiBold.ttf", 13, LATIN),
    ("font_m",  "BarlowSemiCondensed-SemiBold.ttf", 16, LATIN),
    ("font_l",  "BarlowSemiCondensed-Bold.ttf",     22, LATIN),
    ("font_xl", "BarlowSemiCondensed-SemiBold.ttf", 42, DIGITS),
]


def build_vlw(path, px, codepoints):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    glyphs = []
    for cp in codepoints:
        ch = chr(cp)
        # skip code points the font does not contain (Pillow renders .notdef)
        try:
            if font.getmask(ch).getbbox() is None and not ch.isspace():
                continue
        except Exception:
            continue
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = int(round(font.getlength(ch)))
        img = Image.new("L", (max(1, w), max(1, h)), 0)
        if w and h:
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        data = img.tobytes() if (w and h) else b""
        if w > 255 or h > 255 or adv > 255 or not (-128 <= x0 <= 127):
            raise SystemExit(f"glyph {cp:#x} too large for VLW")
        glyphs.append((cp, h, w, adv, -y0, x0, data))
    out = bytearray()
    out += struct.pack(">6i", len(glyphs), 11, px, 0, ascent, descent)
    for cp, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", cp, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    name = os.path.splitext(os.path.basename(path))[0].encode()
    out += bytes([len(name)]) + name + b"\0" + bytes([len(name)]) + name + b"\0" + b"\x01"
    zero = next(g for g in glyphs if g[0] == ord("0"))
    metrics = {"ASCENT": ascent, "DESCENT": descent, "DIGIT_TOP": ascent - zero[4],
               "DIGIT_H": zero[1], "DIGIT_ADV": max(g[3] for g in glyphs if chr(g[0]).isdigit())}
    return bytes(out), len(glyphs), metrics


def write_header(name, data, count, src, px, metrics):
    os.makedirs(OUT_DIR, exist_ok=True)
    lines = [
        "// Generated by tools/gen_fonts.py - do not edit.",
        f"// Source: {src} @ {px}px, {count} glyphs, {len(data)} bytes.",
        "// Barlow Semi Condensed (c) The Barlow Project Authors, SIL Open Font License 1.1.",
        "#pragma once",
        "#include <stdint.h>",
        "#include <pgmspace.h>",
    ]
    for k, v in metrics.items():
        lines.append(f"#define {name.upper()}_{k} {v}")
    lines.append(f"const uint8_t {name.upper()}[] PROGMEM = {{")
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    with open(os.path.join(OUT_DIR, name + ".h"), "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    for name, file, px, cps in FONTS:
        path = os.path.join(FONT_DIR, file)
        data, count, metrics = build_vlw(path, px, cps)
        write_header(name, data, count, file, px, metrics)
        print(f"{name}: {count} glyphs, {len(data)} bytes")


if __name__ == "__main__":
    sys.exit(main())
