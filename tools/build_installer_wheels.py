#!/usr/bin/env python3
"""Download the exact Python wheels the Windows installer needs (offline
install of esptool + pyserial for 64-bit Windows, Python 3.12) and write a
hash-locked requirements file.

    python3 tools/build_installer_wheels.py

Output: installer/wheels/*.whl and installer/requirements-win.lock
"""
import glob
import hashlib
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INST = os.path.join(ROOT, "installer")
WHEELS = os.path.join(INST, "wheels")

PINS = [
    "esptool==4.8.1",       # sdist only on PyPI -> pure-Python wheel built locally
    "pyserial==3.5",
    "bitstring==4.2.3",
    "bitarray==2.9.3",      # bitstring 4.2.3 requires bitarray <3
    "cryptography==43.0.3",
    "cffi==1.17.1",
    "pycparser==2.22",
    "ecdsa==0.19.0",
    "six==1.16.0",
    "reedsolo==1.7.0",
    "PyYAML==6.0.2",
    "intelhex==2.3.0",
    "argcomplete==3.5.1",   # only used on non-Windows systems
]

PLATFORM = ["--platform", "win_amd64", "--python-version", "3.12", "--implementation", "cp",
            "--abi", "cp312", "--abi", "abi3", "--abi", "none", "--only-binary=:all:"]


def run(cmd):
    print("+", " ".join(cmd))
    subprocess.check_call(cmd)


def norm(name):
    return re.sub(r"[-_.]+", "_", name).lower()


def main():
    shutil.rmtree(WHEELS, ignore_errors=True)
    os.makedirs(WHEELS)
    pip = [sys.executable, "-m", "pip"]
    run(pip + ["wheel", "-q", "--no-deps", PINS[0], "-w", WHEELS])
    run(pip + ["download", "-q", "--no-deps", "-d", WHEELS] + PLATFORM + PINS[1:])
    wheels = glob.glob(os.path.join(WHEELS, "*.whl"))
    lines = ["# Offline install for Windows x64 + Python 3.12. Generated by tools/build_installer_wheels.py"]
    for pin in PINS:
        name, ver = pin.split("==")
        match = [w for w in wheels if norm(os.path.basename(w).split("-")[0]) == norm(name)
                 and os.path.basename(w).split("-")[1] == ver]
        if len(match) != 1:
            raise SystemExit(f"wheel for {pin} not found: {match}")
        digest = hashlib.sha256(open(match[0], "rb").read()).hexdigest()
        lines.append(f"{pin} --hash=sha256:{digest}")
    with open(os.path.join(INST, "requirements-win.lock"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    # verify that the set resolves offline for Windows/Python 3.12
    target = os.path.join(ROOT, ".hostbuild", "wheel-check")
    shutil.rmtree(target, ignore_errors=True)
    run(pip + ["install", "-q", "--dry-run", "--no-index", "--find-links", WHEELS, "--require-hashes",
               "-r", os.path.join(INST, "requirements-win.lock"), "--target", target] + PLATFORM)
    print("OK:", len(wheels), "wheels, lock file verified")


if __name__ == "__main__":
    main()
