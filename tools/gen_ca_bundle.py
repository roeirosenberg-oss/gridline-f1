#!/usr/bin/env python3
"""Generate the TLS root-certificate bundle compiled into the firmware.

Source: the Mozilla CA root store as packaged by the Python "certifi" project.
Output: src/certs/ca_bundle.h, in the binary format expected by
arduino-esp32's WiFiClientSecure::setCACertBundle() (the ESP-IDF
x509_crt_bundle format: big-endian count, then per certificate
[u16 subject_len][u16 pubkey_len][subject DER][SubjectPublicKeyInfo DER],
sorted by subject DER so the firmware can binary-search issuers).

The generator refuses to run if the bundle would contain a certificate from
a local interception/development proxy (anything not in certifi's file).

To update the trust store in the future:
    py -3.12 -m pip install --upgrade certifi cryptography
    py -3.12 tools/gen_ca_bundle.py
    (then rebuild and reflash the firmware)
"""
import datetime
import hashlib
import os
import struct
import sys

import certifi
from cryptography import x509
from cryptography.hazmat.primitives import serialization

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "certs", "ca_bundle.h")
# Certificates that must never be trusted by the device (development proxies).
FORBIDDEN_FILES = ["/root/.ccr/agent-proxy-ca.crt", "/root/.ccr/ca-bundle.crt"]


def load_pem_bundle(path):
    with open(path, "rb") as f:
        data = f.read()
    return x509.load_pem_x509_certificates(data)


def main():
    src = certifi.where()
    certs = load_pem_bundle(src)
    now = datetime.datetime.now(datetime.timezone.utc)
    valid = [c for c in certs if c.not_valid_after_utc > now]
    # SHA-256 fingerprints of certificates found in development-proxy bundles
    from cryptography.hazmat.primitives import hashes
    forbidden = set()
    for p in FORBIDDEN_FILES:
        if os.path.exists(p):
            for c in load_pem_bundle(p):
                forbidden.add(c.fingerprint(hashes.SHA256()))
    certifi_fps = {c.fingerprint(hashes.SHA256()) for c in certs}
    proxy_only = [fp for fp in forbidden if fp not in certifi_fps]
    for c in valid:
        if c.fingerprint(hashes.SHA256()) in proxy_only:
            raise SystemExit("refusing: proxy certificate found in bundle")

    entries = []
    for c in valid:
        name = c.subject.public_bytes()
        key = c.public_key().public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
        entries.append((name, key, c))
    entries.sort(key=lambda e: e[0])
    blob = bytearray(struct.pack(">H", len(entries)))
    for name, key, _ in entries:
        blob += struct.pack(">HH", len(name), len(key)) + name + key
    sha = hashlib.sha256(blob).hexdigest()
    names = [e[2].subject.rfc4514_string() for e in entries]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("// Generated by tools/gen_ca_bundle.py - do not edit.\n")
        f.write(f"// Source: Mozilla CA store via certifi {certifi.__version__} ({len(certs)} roots, "
                f"{len(valid)} valid on {now:%Y-%m-%d}).\n")
        f.write(f"// Bundle: {len(entries)} certificates, {len(blob)} bytes, sha256 {sha}\n")
        f.write("// Includes (sample): " + "; ".join(n for n in names if "ISRG" in n or "GTS Root" in n
                                                       or "Amazon Root" in n or "DigiCert Global Root G2" in n
                                                       or "USERTrust RSA" in n) + "\n")
        f.write("#pragma once\n#include <stdint.h>\n")
        f.write(f"#define GL_CA_BUNDLE_COUNT {len(entries)}\n")
        f.write(f"#define GL_CA_BUNDLE_SOURCE \"certifi {certifi.__version__}\"\n")
        f.write("static const uint8_t GL_CA_BUNDLE[] = {\n")
        for i in range(0, len(blob), 24):
            f.write("  " + ",".join(f"0x{b:02x}" for b in blob[i:i + 24]) + ",\n")
        f.write("};\n")
    print(f"certifi {certifi.__version__}: {len(entries)} certificates, {len(blob)} bytes, sha256 {sha}")
    print(f"proxy certificates excluded: {len(proxy_only)}")
    for key in ("ISRG Root X1", "ISRG Root X2", "GTS Root R1", "GTS Root R4", "Amazon Root CA 1",
                "DigiCert Global Root G2", "USERTrust RSA", "Baltimore"):
        print(f"  {key:26s} {'yes' if any(key in n for n in names) else 'NO'}")


if __name__ == "__main__":
    sys.exit(main())
